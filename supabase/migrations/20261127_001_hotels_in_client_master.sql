-- One hotel list: client_master. partner_clients duplicated it, was never
-- filled, and is removed. Hotels are referred to by their code
-- (client_master.client_id, e.g. CLT-001), as the hotel dashboards already do.
-- All or nothing: if any step fails, nothing changes.

BEGIN;

-- 1. client_master gets a row id and a hotel code automatically, so new
--    hotels can be added from the dashboard.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'client_master' AND column_name = 'id'
      AND (column_default IS NOT NULL OR is_identity = 'YES')
  ) THEN
    ALTER TABLE public.client_master ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    PERFORM setval(
      pg_get_serial_sequence('public.client_master', 'id'),
      (SELECT COALESCE(MAX(id), 0) + 1 FROM public.client_master),
      false
    );
  END IF;
END $$;

CREATE SEQUENCE IF NOT EXISTS public.client_master_code_seq;
SELECT setval(
  'public.client_master_code_seq',
  COALESCE((SELECT MAX(substring(client_id FROM '^CLT-(\d+)$')::int) FROM public.client_master), 0) + 1,
  false
);

-- CLT-001 … CLT-999, then CLT-1000 and up.
CREATE OR REPLACE FUNCTION public.next_client_code() RETURNS text
LANGUAGE sql VOLATILE AS $$
  SELECT 'CLT-' || CASE WHEN n < 1000 THEN lpad(n::text, 3, '0') ELSE n::text END
  FROM nextval('public.client_master_code_seq') AS n
$$;

ALTER TABLE public.client_master
  ALTER COLUMN client_id SET DEFAULT public.next_client_code(),
  ALTER COLUMN client_id SET NOT NULL,
  ADD CONSTRAINT client_master_client_id_key UNIQUE (client_id);

-- 2. The outreach settings that only partner_clients had.
ALTER TABLE public.client_master
  ADD COLUMN outreach_mode TEXT NOT NULL DEFAULT 'approve_once'
    CHECK (outreach_mode IN ('approve_once', 'standing_authorisation', 'client_sends_each_wave')),
  ADD COLUMN authorisation_doc_url TEXT,
  ADD COLUMN assessment_deadline DATE,
  ADD COLUMN reminder_max_count INT NOT NULL DEFAULT 6,
  ADD COLUMN reminder_window_days INT NOT NULL DEFAULT 28,
  ADD COLUMN reminder_min_gap_hours INT NOT NULL DEFAULT 48,
  ADD COLUMN created_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

-- Existing hotels: "Joined" shows their account start date.
UPDATE public.client_master SET created_at = account_start_date WHERE account_start_date IS NOT NULL;

-- 3. Tables that pointed at partner_clients now point at the hotel code.
--    (None of them had a hotel set; any value that isn't a hotel code makes
--    the new link fail, and the whole change rolls back.)
ALTER TABLE public.partner_client_supplier_links DROP CONSTRAINT IF EXISTS partner_client_supplier_links_client_id_fkey;
ALTER TABLE public.partner_client_supplier_links ALTER COLUMN client_id TYPE TEXT USING client_id::text;
ALTER TABLE public.partner_client_supplier_links ADD CONSTRAINT partner_client_supplier_links_client_id_fkey
  FOREIGN KEY (client_id) REFERENCES public.client_master(client_id) ON UPDATE CASCADE ON DELETE CASCADE;

ALTER TABLE public.partner_invitations DROP CONSTRAINT IF EXISTS partner_invitations_client_id_fkey;
ALTER TABLE public.partner_invitations ALTER COLUMN client_id TYPE TEXT USING client_id::text;
ALTER TABLE public.partner_invitations ADD CONSTRAINT partner_invitations_client_id_fkey
  FOREIGN KEY (client_id) REFERENCES public.client_master(client_id) ON UPDATE CASCADE ON DELETE SET NULL;

ALTER TABLE public.assessment_pipeline DROP CONSTRAINT IF EXISTS assessment_pipeline_client_id_fkey;
ALTER TABLE public.assessment_pipeline ALTER COLUMN client_id TYPE TEXT USING client_id::text;
ALTER TABLE public.assessment_pipeline ADD CONSTRAINT assessment_pipeline_client_id_fkey
  FOREIGN KEY (client_id) REFERENCES public.client_master(client_id) ON UPDATE CASCADE ON DELETE SET NULL;

ALTER TABLE public.score_versions DROP CONSTRAINT IF EXISTS score_versions_client_id_fkey;
ALTER TABLE public.score_versions ALTER COLUMN client_id TYPE TEXT USING client_id::text;
ALTER TABLE public.score_versions ADD CONSTRAINT score_versions_client_id_fkey
  FOREIGN KEY (client_id) REFERENCES public.client_master(client_id) ON UPDATE CASCADE ON DELETE SET NULL;

ALTER TABLE public.review_queue_flags DROP CONSTRAINT IF EXISTS review_queue_flags_client_id_fkey;
ALTER TABLE public.review_queue_flags ALTER COLUMN client_id TYPE TEXT USING client_id::text;
ALTER TABLE public.review_queue_flags ADD CONSTRAINT review_queue_flags_client_id_fkey
  FOREIGN KEY (client_id) REFERENCES public.client_master(client_id) ON UPDATE CASCADE ON DELETE SET NULL;

ALTER TABLE public.list_uploads DROP CONSTRAINT IF EXISTS list_uploads_client_id_fkey;
ALTER TABLE public.list_uploads ALTER COLUMN client_id TYPE TEXT USING client_id::text;
ALTER TABLE public.list_uploads ADD CONSTRAINT list_uploads_client_id_fkey
  FOREIGN KEY (client_id) REFERENCES public.client_master(client_id) ON UPDATE CASCADE ON DELETE SET NULL;

-- 4. Remove partner_clients. No CASCADE: if anything still depends on it,
--    this fails and nothing changes.
DROP TABLE public.partner_clients;

COMMIT;

-- The API reads the new links straight away.
NOTIFY pgrst, 'reload schema';
